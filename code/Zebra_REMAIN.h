/*!
 * @file    Zebra_REMAIN.h
 * @brief   斑马线起跑/停车识别
 * @note    斑马线既是起点也是终点。做法：在摄像头原始灰度图的下部若干行里数"窄黑条"，
 *          一条合格的斑马线在同一帧里会有 >=5 根等宽的窄黑条、且这种行 >=3 行。
 *          状态机：等待 -> 看到斑马线就出发 -> 斑马线离开视野后才允许再次触发 -> 再看到就停车并锁定。
 *
 * Created on: 2026年10月23日
 * Author: Freed
 */

#ifndef CODE_ZEBRA_REMAIN_H_
#define CODE_ZEBRA_REMAIN_H_

#include "zf_common_headfile.h"

//-------------------------------------------------------------------------------------------------------------------
// 宏定义
//-------------------------------------------------------------------------------------------------------------------
#define ZEBRA_EN                (1)         // 1-启用斑马线起停（控制环只在 RUN 状态才走）
#define ZEBRA_DIS_EN            (1)         // 1-在屏幕 Y1 行右侧显示状态字母

#define ZEBRA_ROW_TOP           (82)        // 扫描起始行（画面偏下，斑马线离车头最近的位置）
#define ZEBRA_ROW_BOT           (118)       // 扫描结束行
#define ZEBRA_BAR_MIN_PX        (2)         // 一根黑条最窄几个像素
#define ZEBRA_BAR_MAX_PX        (22)        // 一根黑条最宽几个像素（再宽就是蓝地垫/阴影，不是斑马线）
#define ZEBRA_MIN_BARS          (5)         // 一行里至少几根黑条才算斑马线
#define ZEBRA_MIN_ROWS          (3)         // 至少几行同时满足
#define ZEBRA_WHITE_MIN         (0.25f)     // 这一行里白像素至少要占多少（保证看的是赛道不是背景）

#define ZEBRA_HIT_FRAMES        (2)         // 连续几帧检测到才认账（去抖）
#define ZEBRA_CLEAR_FRAMES      (25)        // 斑马线要连续消失多少帧才认账（防抖，0.5s @50fps）
#define ZEBRA_RUN_MIN_FRAMES    (150)       // 发车后至少跑多少帧才允许判终点（3s @50fps，防刚起步就停）

//-------------------------------------------------------------------------------------------------------------------
// 结构体
//-------------------------------------------------------------------------------------------------------------------
typedef struct
{
    uint8   state;                          // 0-等待出发  1-行驶中  2-已到终点
    uint8   hit;                            // 本帧检测到斑马线
    uint8   votes;                          // 本帧满足条件的行数
    uint8   hit_cnt;                        // 连续检测到的帧数
    uint8   clear_cnt;                      // 连续没检测到的帧数
    uint8   run_cnt;                        // 行驶了多少帧
    uint8   armed;                          // 1-起点已经跑过去了，再看到斑马线就是终点
} zebra_info_struct;

extern zebra_info_struct zebra_info;

//-------------------------------------------------------------------------------------------------------------------
// 函数
//-------------------------------------------------------------------------------------------------------------------
void    Zebra_Init            (void);
void    Zebra_Scan            (void);
void    Zebra_Show_On_TFT180  (void);

#endif
